import { z } from "zod";

/** Contrat C7 : code d'explication + paramètres chiffrés (Agent.md §4, §8). */
export const schemaCodeExplication = z.object({
  /** Version du contrat C7 (obligatoire, Agent.md §4). */
  version: z.number().int().positive(),
  /** Code stable, sans texte joueur (ex. `MASSE_DEPASSE`). */
  code: z.string().min(1),
  /** Paramètres chiffrés (écart en kg, pourcentage, …). */
  params: z.record(z.string(), z.union([z.number(), z.string()])),
});
export type CodeExplication = z.infer<typeof schemaCodeExplication>;

